#include<iostream>
using namespace std;
int main(){
    char ch='1';
    cout<<ch << endl;


    //ascii value
    char x='a';
    char y='A';
    char z='0';                 //note:these 3 values
    cout<<(int)x << endl;       //a=97
    cout<< (int)y<< endl;       //A=65
    cout<< (int)z<< endl;       //0=48

    return 0;
}