#include<iostream>
using namespace std;
int main(){

    //calc area of circle,square and rectangle

    //area of circle of radius 5!
    float radius=5;
    cout<<"the radius of the circle is : "<<3.14*radius*radius <<endl;

    //area of rectangle(l=6,b=9)
    float length=6;
    float breadth=9;
    cout<<"the area of rectangle is: "<<length*breadth <<endl;

    //area of the square!
    float side=10;
    cout<<"the area of the square: "<<side*side <<endl;

    return 0;
}